  <h2 class="fr-pt-8w">La publication des cahiers de doléances du Grand Débat national</h2>
  <p>
    Dans le cadre du Grand Débat national de <time>2019</time>, les Français ont rempli près de <b>20 000 cahiers de doléances dans les mairies</b>. Ces documents constituent un témoignage inédit de la parole citoyenne et des aspirations des Français. Pendant plusieurs années, ces cahiers étaient consultables uniquement sur dérogation. Ils sont désormais <b>accessibles à tous sans dérogation dans les archives nationales et départementales</b>. La prochaine étape est de les rendre consultables directement sur Internet.
  </p>

